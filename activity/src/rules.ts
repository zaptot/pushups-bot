/** Кнопка «Правила» для шапки: открывает правила текущей игры. */
export function rulesButton(gameId: () => string | null): HTMLButtonElement {
  const button = el('button', 'rules-button hidden');
  button.title = 'Правила игры';
  button.setAttribute('aria-label', 'Правила игры');
  button.append(el('span', 'rules-q', '?'), el('span', 'rules-label', 'Правила'));
  button.addEventListener('click', () => {
    const id = gameId();
    if (id && rules[id]) {
      showRules(rules[id]);
    }
  });
  return button;
}

export const hasRules = (gameId: string): boolean => gameId in rules;

function showRules(r: Rules): void {
  const body = el('div', 'rules-body');
  body.append(el('h2', 'rules-title', `Правила: ${r.title}`));
  for (const section of [...r.sections, common]) {
    const list = el('ul');
    for (const item of section.items) {
      list.append(el('li', '', item));
    }
    body.append(el('h3', '', section.title), list);
  }
  // клик по тексту не закрывает правила: можно выделять и листать
  body.addEventListener('click', (e) => e.stopPropagation());
  const close = el('button', 'primary overlay-close', 'Понятно');
  showOverlay('rules', `Правила: ${r.title}`, [body, close], close);
}
